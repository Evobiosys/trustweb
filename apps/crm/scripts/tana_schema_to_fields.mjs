// Tana #person supertag schema (markdown) -> src/person_fields.ts. Schema only (names, ids, options): no person data.
//   node scripts/tana_schema_to_fields.mjs <person-schema.md> [out.ts]   (default out: src/person_fields.ts)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const TYPES = { Content: 'content', Checkbox: 'checkbox', Options: 'options', URL: 'url' }

/** Field label without markup: trailing colon and spaces dropped. */
export const fieldLabel = (s) => s.replace(/:\s*$/, '').trim()

/** @returns {object[]} fields in schema order */
export function parseSchema(md) {
  const fields = []
  let cur = null
  for (const line of md.split('\n')) {
    const f = /^- \*\*(.+?)\*\* \(id:([^)]+)\):: (.+)$/.exec(line)
    if (f) {
      const inst = /^Instance of #(.+?) \(id:([^)]+)\)$/.exec(f[3])
      cur = { id: f[2], tanaAttributeId: f[2], label: fieldLabel(f[1]), type: inst ? 'instance' : TYPES[f[3].trim()] ?? 'content', description: '' }
      if (inst) cur.instanceTag = { id: inst[2], name: inst[1] }
      if (cur.type === 'options') cur.options = []
      fields.push(cur)
      continue
    }
    const o = /^ {2}- (.+) \(id:([^)]+)\)$/.exec(line)
    if (o && cur?.options) { cur.options.push({ id: o[2], label: o[1] }); continue }
    const d = /^ {2}<description>(.*)<\/description>$/.exec(line)
    if (d && cur) cur.description = d[1].replace(/<[^>]+>/g, '').trim()
  }
  return fields
}

const TYPE_DECL = `export interface PersonField {
  /** Same as tanaAttributeId for Tana fields; 'tw-…' for TrustWeb-only fields. */
  id: string
  tanaAttributeId: string | null
  label: string
  type: 'content' | 'checkbox' | 'options' | 'url' | 'instance'
  options?: { id: string; label: string }[]
  instanceTag?: { id: string; name: string }
  description: string
}
`

const TRUSTWEB_ONLY = [
  { id: 'tw-famous', tanaAttributeId: null, label: 'famous, no intent to connect', type: 'checkbox', description: 'TrustWeb only: no Tana field yet' },
  {
    id: 'tw-ring', tanaAttributeId: null, label: 'relationship', type: 'options', description: 'TrustWeb only: the ring',
    options: [['close', 'Close'], ['friend', 'Friend'], ['acquaintance', 'Acquaintance'], ['intending', 'Intending']].map(([id, label]) => ({ id, label })),
  },
]

export function render(fields) {
  return `// GENERATED by scripts/tana_schema_to_fields.mjs from the Tana #person schema. Do not edit; regenerate.
// Field names and ids only, no person data.
${TYPE_DECL}
export const PERSON_FIELDS: readonly PersonField[] = ${JSON.stringify([...fields, ...TRUSTWEB_ONLY], null, 2)}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [schema, out = fileURLToPath(new URL('../src/person_fields.ts', import.meta.url))] = process.argv.slice(2)
  if (!schema) { console.error('usage: tana_schema_to_fields.mjs <person-schema.md> [out.ts]'); process.exit(2) }
  const fields = parseSchema(readFileSync(schema, 'utf8'))
  writeFileSync(out, render(fields))
  console.log(`${fields.length} Tana fields + ${TRUSTWEB_ONLY.length} TrustWeb-only -> ${out}`)
}
