// Tana #person supertag schema (markdown) -> src/person_fields.ts. Schema only (names, ids, options): no person data.
//   node scripts/tana_schema_to_fields.mjs <person-schema.md> [out.ts]          (default out: src/person_fields.ts)
//   node scripts/tana_schema_to_fields.mjs <environment-schema.md> <out.ts> environment
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const TYPES = { Content: 'content', Checkbox: 'checkbox', Options: 'options', URL: 'url', Date: 'date' }

/** Field label without markup: trailing colon and spaces dropped. */
export const fieldLabel = (s) => s.replace(/:\s*$/, '').trim()

/** @returns {object[]} fields in schema order */
export function parseSchema(md) {
  const fields = []
  let cur = null
  for (const line of md.split('\n')) {
    const f = /^- \*\*(.+?)\*\* \(id:([^)]+)\):: (.+)$/.exec(line)
    if (f) {
      const inst = /^Instance of #(.+?) \(id:([^)]+)\)$/.exec(f[3])
      const num = inst?.[1] === 'Number'
      cur = { id: f[2], tanaAttributeId: f[2], label: fieldLabel(f[1]), type: num ? 'number' : inst ? 'instance' : TYPES[f[3].trim()] ?? 'content', description: '' }
      if (inst && !num) cur.instanceTag = { id: inst[2], name: inst[1] }
      if (cur.type === 'options') cur.options = []
      fields.push(cur)
      continue
    }
    const o = /^ {2}- (.+) \(id:([^)]+)\)$/.exec(line)
    if (o && cur?.options) { cur.options.push({ id: o[2], label: o[1] }); continue }
    const d = /^ {2}<description>(.*)<\/description>$/.exec(line)
    if (d && cur) cur.description = d[1].replace(/<[^>]+>/g, '').trim()
  }
  return fields
}

const TYPE_DECL = `export interface PersonField {
  /** Same as tanaAttributeId for Tana fields; 'tw-…' for TrustWeb-only fields. */
  id: string
  tanaAttributeId: string | null
  label: string
  type: 'content' | 'checkbox' | 'options' | 'url' | 'instance' | 'number' | 'date'
  options?: { id: string; label: string }[]
  instanceTag?: { id: string; name: string }
  description: string
}
`

const RING_LABELS = [['close', 'Close friend'], ['friend', 'Friend'], ['acquaintance', 'Acquaintance'], ['intending', 'Intending to connect']]
const FAV_LABELS = [['email', 'Email'], ['phone', 'Phone call'], ['sms', 'SMS'], ['signal', 'Signal'], ['whatsapp', 'WhatsApp'], ['matrix', 'Matrix']]
const opts = (pairs) => pairs.map(([id, label]) => ({ id, label }))
const tw = (id, label, type, description, options) => ({ id, tanaAttributeId: null, label, type, description, ...(options ? { options: opts(options) } : {}) })

/** TrustWeb-only fields per entity kind: no Tana attribute, so they never sync. */
const TRUSTWEB_ONLY = {
  person: [
    tw('tw-first', 'First name', 'content', 'TrustWeb only: from the Tana name until typed'),
    tw('tw-context', 'Context', 'content', 'TrustWeb only: met in which context, or intending to connect'),
    tw('tw-ring', 'Ring', 'options', 'TrustWeb only', RING_LABELS),
    tw('tw-fav', 'Favourite way to connect', 'options', 'TrustWeb only', FAV_LABELS),
    tw('tw-non-responsive', 'non-responsive', 'checkbox', 'does not answer messages or asks; shown greyed in lists, excluded from asks by default'),
  ],
  environment: [tw('tw-context', 'Context', 'content', 'TrustWeb only')],
}

const CONST = { person: 'PERSON_FIELDS', environment: 'ENVIRONMENT_FIELDS' }
/** Tana "ring" and "ring approved": written by the ring sync (src/tana_sync.ts), never shown as editable fields. */
const SYNC_ONLY = new Set(['rVfw62lb7BYD', '_7wgarGd90ZR'])

export function render(fields, kind = 'person') {
  const decl = kind === 'person' ? TYPE_DECL : "import type { PersonField } from './person_fields'\n"
  return `// GENERATED by scripts/tana_schema_to_fields.mjs from the Tana #${kind} schema. Do not edit; regenerate.
// Field names and ids only, no person data.
${decl}
export const ${CONST[kind]}: readonly PersonField[] = ${JSON.stringify([...fields.filter((f) => !SYNC_ONLY.has(f.id)), ...TRUSTWEB_ONLY[kind]], null, 2)}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [schema, out = fileURLToPath(new URL('../src/person_fields.ts', import.meta.url)), kind = 'person'] = process.argv.slice(2)
  if (!schema || !CONST[kind]) { console.error('usage: tana_schema_to_fields.mjs <schema.md> [out.ts] [person|environment]'); process.exit(2) }
  const fields = parseSchema(readFileSync(schema, 'utf8'))
  writeFileSync(out, render(fields, kind))
  console.log(`${fields.length} Tana fields + ${TRUSTWEB_ONLY[kind].length} TrustWeb-only -> ${out}`)
}
