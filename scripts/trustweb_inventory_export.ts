/**
 * Personal TrustWeb inventory exporter. Runs on Jakob's Mac only.
 *
 *   node_modules/.bin/tsx scripts/trustweb_inventory_export.ts [options]
 *
 * Reads, READ-ONLY:
 *   - Tana, Library > "Personal TrustWeb Inventory" (node qAo6KedrMFrC): its
 *     "referenced" groups and items and its "inbox", one hop into each item
 *     (title + first line), through ~/.claude/scripts/tana_mcp.sh. Only
 *     get_children is ever called; --write is never passed.
 *   - --choices <kimi-ticked.json>: the review page's saved choices.
 *   - --mac-folder <dir>: *.txt / *.md lines; "+ " marks a line.
 * Writes (files 0600, folder 0700), all on this Mac:
 *   (a) <out>/personal-inventory_full.json      every line, source, verdict
 *   (c) the review file (--review)              what WOULD leave, what stays, why
 *   (d) <out>/trustweb-inventory-import.json    every line, for your own phone
 *   (b) <out>/personal-inventory_server.json    ONLY with --send: the marked lines
 * Default is a DRY RUN: nothing leaves this Mac. --send additionally needs
 * --host, a terminal, a review file regenerated by this very run, and your
 * "y" after the lines are shown; then the server file replaces the personal
 * front door's inventory on that host and the unit restarts.
 *
 * Options: --choices <file> --mac-folder <dir> --out <dir> --review <file>
 *          --tana-root <id> --no-tana --by <name> --send --host questhub|sebra
 */
import { execFile, spawn } from 'node:child_process'
import { chmodSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import path from 'node:path'
import { createInterface } from 'node:readline/promises'
import { randomBytes } from 'node:crypto'
import {
  TanaReadTool, assertServerFileSafe, buildExport, fullFile, importFile, parseChoices, parseFolderLine,
  readTanaInventory, renderReview, serverFile, wireContext,
} from '../services/trustweb-peer/inventory_export'
import type { Candidate, ServerFile, TanaCall } from '../services/trustweb-peer/inventory_export'

const INVENTORY_ROOT = 'qAo6KedrMFrC'
const TANA_SCRIPT = process.env.TW_TANA_MCP ?? path.join(homedir(), '.claude/scripts/tana_mcp.sh')
const DEFAULT_OUT = path.join(homedir(), '.trustweb', 'personal-inventory')
const READ_TOOLS = new Set<string>(Object.values(TanaReadTool))

/** Where the personal front door keeps its inventory (scripts/deploy_trustweb_peer.sh --instance personal). */
const PERSONAL_UNIT = 'trustweb-peer-personal'
const PERSONAL_INVENTORY = '/etc/trustweb-peer-personal/inventory.json'
const PERSONAL_HEALTH_PORT = 8962

export enum Host {
  Questhub = 'questhub',
  Sebra = 'sebra',
}

interface Args {
  choices?: string
  macFolder?: string
  out: string
  review?: string
  tanaRoot: string
  tana: boolean
  by: string
  send: boolean
  host?: Host
}

function usage(msg: string): never {
  console.error(msg)
  console.error('usage: trustweb_inventory_export.ts [--choices <file>] [--mac-folder <dir>] [--out <dir>] [--review <file>] [--tana-root <id>] [--no-tana] [--by <name>] [--send --host questhub|sebra]')
  process.exit(2)
}

export function parseArgs(argv: readonly string[]): Args {
  const a: Args = { out: DEFAULT_OUT, tanaRoot: INVENTORY_ROOT, tana: true, by: 'Jakob', send: false }
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i]
    const value = (): string => {
      const v = argv[++i]
      if (v === undefined || v.startsWith('--')) usage(`${flag} needs a value`)
      return v
    }
    switch (flag) {
      case '--choices': a.choices = path.resolve(value()); break
      case '--mac-folder': a.macFolder = path.resolve(value()); break
      case '--out': a.out = path.resolve(value()); break
      case '--review': a.review = path.resolve(value()); break
      case '--tana-root': a.tanaRoot = value(); break
      case '--no-tana': a.tana = false; break
      case '--by': a.by = value().trim() || usage('--by needs a name'); break
      case '--send': a.send = true; break
      case '--host': {
        const h = value()
        if (!(Object.values(Host) as string[]).includes(h)) usage(`--host must be one of ${Object.values(Host).join(', ')}`)
        a.host = h as Host
        break
      }
      default: usage(`unknown option ${flag}`)
    }
  }
  if (a.send && !a.host) usage('--send needs --host questhub|sebra (where the personal front door runs)')
  return a
}

/** tana_mcp.sh, read tools only; the write flag can never reach it from here. */
export function tanaViaScript(script: string): TanaCall {
  return (tool, args) => new Promise((resolve, reject) => {
    if (!READ_TOOLS.has(tool)) { reject(new Error(`refused: ${tool} is not a read tool`)); return }
    execFile(script, [tool, JSON.stringify(args)], { maxBuffer: 16 * 1024 * 1024, timeout: 60_000 }, (err, stdout) => {
      if (err) { reject(new Error(`tana ${tool} failed: ${err.message.split('\n')[0]}`)); return }
      try { resolve(JSON.parse(stdout)) } catch { reject(new Error(`tana ${tool}: not JSON`)) }
    })
  })
}

/**
 * The Mac folder's lines. Only REGULAR files that sit in the folder itself
 * count: a symlink (to a file anywhere else on the Mac), a subfolder or a
 * device is skipped and named, so no "+ " line can come from outside it.
 */
export function readFolder(dir: string, warn: (msg: string) => void = (m) => console.log(m)): Candidate[] {
  const out: Candidate[] = []
  for (const f of readdirSync(dir).filter((n) => /\.(txt|md)$/i.test(n)).sort()) {
    const st = lstatSync(path.join(dir, f))
    if (!st.isFile()) { warn(`skipped ${f}: not a regular file in the folder (a symlink or folder is never read)`); continue }
    for (const raw of readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/)) {
      const c = parseFolderLine(raw, f)
      if (c) out.push(c)
    }
  }
  return out
}

function writePrivate(file: string, content: string): void {
  mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 })
  writeFileSync(file, content, { mode: 0o600 })
  chmodSync(file, 0o600)
}

function localDay(d: Date): string {
  const p = (n: number): string => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`
}

/** The send guard: the review file must exist, be non-empty, and carry THIS run's id (it was regenerated now). */
export function reviewIsFresh(file: string, runId: string, startedAt: number): boolean {
  if (!existsSync(file)) return false
  const st = statSync(file)
  if (st.size === 0 || st.mtimeMs + 1000 < startedAt) return false
  return readFileSync(file, 'utf8').includes(`run ${runId},`)
}

const SSH_ENV = { ...process.env, SSH_ASKPASS: path.join(homedir(), '.ssh/questhub-jump-askpass'), SSH_ASKPASS_REQUIRE: 'force', DISPLAY: ':0' }

function ssh(host: Host, command: string, stdin?: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const p = spawn('ssh', [host, command], { env: SSH_ENV, stdio: ['pipe', 'pipe', 'inherit'] })
    let out = ''
    p.stdout.on('data', (d: Buffer) => { out += d.toString() })
    p.on('error', reject)
    p.on('close', (code) => (code === 0 ? resolve(out) : reject(new Error(`ssh ${host} exited ${code}`))))
    p.stdin.end(stdin ?? '')
  })
}

/**
 * The one action that sends personal data needs a typed "y" (or "yes").
 * ENTER alone is NO here, unlike the usual "ENTER or y or n": a newline typed
 * ahead during the Tana read, or pasted with the command, would otherwise
 * answer the question before it was read.
 */
export function isExplicitYes(answer: string): boolean {
  const a = answer.trim().toLowerCase()
  return a === 'y' || a === 'yes'
}

async function ask(question: string): Promise<string> {
  const rl = createInterface({ input: process.stdin, output: process.stdout })
  const answer = await rl.question(question)
  rl.close()
  return answer
}

/** What send() needs from the outside world; injected so the tests drive it without a terminal or a host. */
export interface SendDeps {
  ask: (question: string) => Promise<string>
  ssh: (host: Host, command: string, stdin?: string) => Promise<string>
  print: (line: string) => void
}

const REAL_DEPS: SendDeps = { ask, ssh, print: (l) => console.log(l) }

/** Shows exactly what goes over the wire (text and the context the asker sees), asks, then replaces the front door's inventory. Returns whether it sent. */
export async function send(host: Host, file: ServerFile, deps: SendDeps = REAL_DEPS): Promise<boolean> {
  const { print } = deps
  print('--------')
  print(`These ${file.items.length} line(s) would go to your personal front door on ${host}, each exactly as an asker would see it:`)
  for (const it of file.items) print(`  + "${it.text}"  marked "${wireContext(it.preset.by, it.preset.at, it.preset.note)}"`)
  if (!isExplicitYes(await deps.ask('Send them now? Type y to send; n or ENTER sends nothing: '))) { print('not sent'); return false }
  const remote = deps.ssh
  await remote(host, `systemctl cat ${PERSONAL_UNIT} >/dev/null 2>&1 || { echo "the personal front door is not deployed on this host" >&2; exit 3; }`)
  await remote(
    host,
    `set -e; umask 077; t=$(mktemp); cat > "$t"; sudo install -D -m 0600 -o root -g root "$t" ${PERSONAL_INVENTORY}; rm -f "$t"; ` +
      `sudo systemctl restart ${PERSONAL_UNIT}; ` +
      `for i in $(seq 1 15); do curl -fsS -H 'Host: 127.0.0.1:${PERSONAL_HEALTH_PORT}' http://127.0.0.1:${PERSONAL_HEALTH_PORT}/health >/dev/null 2>&1 && break; sleep 1; done`,
    JSON.stringify(file) + '\n',
  )
  const status = await remote(host, `curl -fsS -H 'Host: 127.0.0.1:${PERSONAL_HEALTH_PORT}' http://127.0.0.1:${PERSONAL_HEALTH_PORT}/status`)
  print('front door status: ' + status.trim())
  const preset = (JSON.parse(status) as { presetLines?: unknown }).presetLines
  if (preset !== file.items.length) throw new Error(`the front door reports ${String(preset)} preset lines, expected ${file.items.length}`)
  print(`sent: ${file.items.length} line(s)`)
  return true
}

export async function main(argv: readonly string[]): Promise<void> {
  console.log('... trustweb_inventory_export running ...')
  console.log('--------')
  const startedAt = Date.now()
  const runId = randomBytes(6).toString('hex')
  const args = parseArgs(argv)
  const today = localDay(new Date())
  const candidates: Candidate[] = []
  const inputs: string[] = []
  let knownIds = new Set<string>()
  let readIds: string[] = []

  if (args.tana) {
    const tana = await readTanaInventory(tanaViaScript(TANA_SCRIPT), args.tanaRoot)
    candidates.push(...tana.candidates)
    knownIds = tana.seenIds
    readIds = tana.readIds
    inputs.push(`Tana "Personal TrustWeb Inventory": ${tana.candidates.length} line(s) from ${tana.readIds.length} node(s)`)
  }
  if (args.choices) {
    const c = parseChoices(JSON.parse(readFileSync(args.choices, 'utf8')))
    candidates.push(...c)
    for (const x of c) if (x.tanaNodeId) knownIds.add(x.tanaNodeId)
    inputs.push(`choices file ${args.choices}: ${c.length} ticked line(s), ${c.filter((x) => x.mark).length} allowed in advance`)
  }
  if (args.macFolder) {
    const c = readFolder(args.macFolder)
    candidates.push(...c)
    inputs.push(`Mac folder ${args.macFolder}: ${c.length} line(s), ${c.filter((x) => x.mark).length} marked "+ "`)
  }
  if (!inputs.length) inputs.push('(no source: --no-tana without --choices or --mac-folder)')

  const opts = { today, by: args.by, knownIds }
  const lines = buildExport(candidates, opts)
  const server = serverFile(lines, opts)
  const count = assertServerFileSafe(server, lines, knownIds)

  const fullPath = path.join(args.out, 'personal-inventory_full.json')
  const importPath = path.join(args.out, 'trustweb-inventory-import.json')
  const serverPath = path.join(args.out, 'personal-inventory_server.json')
  const reviewPath = args.review ?? path.join(args.out, 'export-review.txt')
  const files = [`${fullPath}  (a) every line, Mac only`, `${importPath}  (d) for your own phone, every line, "Only me"`]
  if (args.send) files.push(`${serverPath}  (b) the ${count} marked line(s), sent to ${args.host}`)

  writePrivate(fullPath, JSON.stringify(fullFile(lines, opts, readIds), null, 2) + '\n')
  writePrivate(importPath, JSON.stringify(importFile(lines, opts), null, 2) + '\n')
  writePrivate(reviewPath, renderReview(lines, {
    runId,
    by: args.by,
    today,
    generatedAt: new Date().toString(),
    mode: args.send ? 'send' : 'dry run',
    destination: args.host ? `the personal front door on ${args.host}` : 'the personal front door (only with --send; this run sends nothing)',
    inputs,
    files,
  }))

  console.log(`lines: ${lines.length}; would leave this Mac: ${count}; stay: ${lines.length - count}`)
  console.log(`review: ${reviewPath}`)
  console.log(`full:   ${fullPath}`)
  console.log(`import: ${importPath}`)
  if (readIds.length) console.log(`tana nodes read: ${readIds.length} (listed in the full file, tanaNodesRead)`)

  if (!args.send) {
    console.log('--------')
    console.log('dry run: nothing left this Mac')
    return
  }
  if (!process.stdin.isTTY) throw new Error('refused: --send needs a terminal (you confirm the lines yourself)')
  if (!reviewIsFresh(reviewPath, runId, startedAt)) throw new Error('refused: the review file was not regenerated by this run')
  writePrivate(serverPath, JSON.stringify(server, null, 2) + '\n')
  await send(args.host as Host, server)
}

if (/trustweb_inventory_export\.(ts|mjs|js)$/.test(process.argv[1] ?? '')) {
  main(process.argv.slice(2)).catch((e: unknown) => {
    console.error(e instanceof Error ? e.message : String(e))
    process.exit(1)
  })
}
